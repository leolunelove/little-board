export type Status = "pending" | "waiting" | "done";
export type ChecklistItem = { id: string; title: string; done: boolean };
export type TaskImage = { id: string; name: string; src: string };
export type Task = {
  images?: TaskImage[];
  id: string;
  board_id: string;
  title: string;
  note: string;
  checklist?: ChecklistItem[];
  original_request?: string;
  status: Status;
  assigned_to: "me" | "partner" | null;
  sort_order: number;
  created_at: string;
  updated_at: string;
  completed_at: string | null;
};
export type Board = {
  server_revision?: number;
  sync_state?: "synced" | "pending" | "conflict";
  offline?: boolean;
  description?: string;
  code?: string;
  access?: "owner" | "viewer";
  claimed?: boolean;
  invited_email?: string | null;
  id: string;
  title: string;
  updated_at: string;
  tasks: Task[];
};
export type Mode = "owner" | "viewer" | "preview";
